# Read incoming binary block from stdin and write out in hexadecimal text format
# One sample for each channel, per line

import sys
import errno
import time
import serial
import serial.tools.list_ports

BUFFER_SIZE = 128
BLOCK_SIZE = BUFFER_SIZE * 8
 
def find_serial_device():
    '''determines the serial port that the Pico is connected to. On Ubuntu/Raspberry
    Pi, serial ports are in the form '/dev/ttyACMx' where x is an integer 0-7.
    On Windows, serial ports are in the form 'COMx' where x is an integer 1-8'''
    ports = serial.tools.list_ports.comports()
    for port in ports:
        description = port.description
        if 'board in fs mode' in description.lower() or 'serial' in description.lower():
            print(f'{time.ctime()} reader.py, find_serial_device(): Found {port.description}.', file=sys.stderr)
            # port.device contains the name of the port
            return port.device
    print(f"{time.ctime()} reader.py, main(): Couldn't find a suitable serial port.", file=sys.stderr)
    return None
 

def connect(port_name):
    '''Connects to serial port with re-try and backoff in case other services are
    trying to probe the port.'''
    sleeping = [ 0.2, 0.3, 0.5, 1.0, 2.0 ]
    MAX_TRIES = 5
    this_try = 0
    # try to connect five times
    while this_try < MAX_TRIES:
        ser = serial.Serial(port_name, timeout=None)
        if ser.is_open:
            print(f"{time.ctime()} reader.py, connect(): Connected to {port_name}.", file=sys.stderr)
            return ser
        time.sleep(sleeping[this_try])
        this_try = this_try + 1
    print(f"{time.ctime()} reader.py, main(): Failed to connect to serial port.", file=sys.stderr)
    return None


def verify(ser):
    '''Carries out a read test to verify that data is available on the serial port.'''
    bs = bytearray(BLOCK_SIZE)
    # discard anything hanging around in the hardware buffer
    ser.reset_input_buffer()
    # the finite timeout allows doomed verification attempts to exit
    ser.timeout = 4.0
    n = ser.readinto(bs)
    if n == BLOCK_SIZE:
        print(f"{time.ctime()} reader.py, verify(): Data available, looks good.", file=sys.stderr)
        return True
    else:
        print(f"{time.ctime()} reader.py, verify(): Unfortunately there's no data waiting on this port.", file=sys.stderr)
        return False


def read_and_print(ser):
    '''Reads binary data from serial port, and prints as hexadecimal text to stdout.'''
    bs = bytearray(BLOCK_SIZE)
    # we use a 'None' timeout (blocking read) for efficiency, an exception will be thrown if
    # a serial port error occurs
    ser.timeout = None
    while True:
        try:
            # read exactly BLOCKSIZE bytes into bytearray buffer
            ser.readinto(bs)
            # process data as lines of 8 bytes, or 16 hex characters
            hexstr = bs.hex()
            for i in range(0, BLOCK_SIZE*2, 16):
                print(f'{hexstr[i:i+4]} {hexstr[i+4:i+8]} {hexstr[i+8:i+12]} {hexstr[i+12:i+16]}')

        except OSError as e:
            if e.errno == errno.EINTR:
                # continue silently if the read was interrupted by an EINTR signal which can sometimes
                # be generated by other processes that need the bus/CPU
                pass
            elif e.errno == errno.EPIPE:
                # if there is a broken pipe error, bump the exception out to caller
                print(f'{time.ctime()} reader.py, read_and_print(): Broken pipe exception, we need to quit.', file=sys.stderr)
                raise e
            else:
                print(f'{time.ctime()} reader.py, read_and_print(): OSError "{e}" during attempt to read from serial port.', file=sys.stderr)
                break

        except IOError as e:
            print(f'{time.ctime()} reader.py, read_and_print(): IOError "{e}" during attempt to read from serial port.', file=sys.stderr)
            break


def main():
    '''This program needs the Pico to have been set into streaming mode by the 
    pico_control.py program first.'''
    try:
        # The loop is so we can attempt automatic retry for certain error states.
        while True:
            if (port_name := find_serial_device()) \
                    and (ser := connect(port_name)) \
                    and verify(ser):
                # read_and_print() will continue indefinitely if there are no errors
                read_and_print(ser)
                # something went wrong, so we close the port before looping round.
                ser.close()
            else:
                # if any of the predicates return None or False, we quit
                break

    except:
        # we also catch broken pipe and other exceptions here, so that we can clean up
        pass

    finally:
        # There was an error on the way and our reconnection attempts did not work.
        # Make sure we have closed the port if it was opened.
        if 'ser' in locals():
            ser.close()
        print(f'{time.ctime()} reader.py, main(): Exiting after encountering errors.', file=sys.stderr)


if __name__ == '__main__':
    main()


